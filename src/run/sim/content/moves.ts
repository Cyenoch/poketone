export type Archetype =
  | "bolt"
  | "cone"
  | "vortex"
  | "orb"
  | "strike"
  | "barrage"
  | "beam"
  | "spin"
  | "chain"
  | "smite"
  | "nova"
  | "homing"
  | "drain"
  | "lob"
  | "wave"
  | "bloom"
  | "firestorm"
  | "sprinkler"
  | "rod"
  | "tempest"
  | "combo"
  | "weather";
export type UpgradeStat =
  | "dmg"
  | "cd"
  | "count"
  | "area"
  | "speed"
  | "dur"
  | "pierce"
  | "crit"
  | "status";

export type MoveCategory = "physical" | "special" | "status";

export interface MoveDef<Id extends string = MoveId> {
  id: Id;
  name: string;
  type: ElementType;
  archetype: Archetype;
  /** Damage class; status moves deal no direct damage. */
  category: MoveCategory;
  dmg: number;
  cd: number;
  count: number;
  /** Radius, cone length or beam width depending on the archetype. */
  area: number;
  speed: number;
  dur: number;
  pierce: number;
  status?: EnemyStatusId;
  statusChance: number;
  /** Share of the HP a hit actually removes that heals the caster (drain moves). */
  drain?: number;
  /** Made at Bill's machine (content/fusions.ts), never taught by a card; levels are ★ stars. */
  fusion?: true;
  stats: readonly UpgradeStat[];
  ref: string;
}

