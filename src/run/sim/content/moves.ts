import type { ElementType } from "./elements";
import type { EnemyStatusId } from "./statuses";

export type Archetype =
  | "bolt"
  | "cone"
  | "vortex"
  | "orb"
  | "strike"
  | "barrage"
  | "beam"
  | "spin"
  | "chain"
  | "smite"
  | "nova"
  | "homing"
  | "drain"
  | "lob"
  | "wave"
  | "bloom"
  | "firestorm"
  | "sprinkler"
  | "rod";
export type UpgradeStat =
  | "dmg"
  | "cd"
  | "count"
  | "area"
  | "speed"
  | "dur"
  | "pierce"
  | "crit"
  | "status";

export type MoveCategory = "physical" | "special";

export interface MoveDef<Id extends string = MoveId> {
  id: Id;
  name: string;
  type: ElementType;
  archetype: Archetype;
  /** The series' damage class: physical or special items boost only their own (muscle band, wise glasses). */
  category: MoveCategory;
  dmg: number;
  cd: number;
  count: number;
  /** Radius, cone length or beam width depending on the archetype. */
  area: number;
  speed: number;
  dur: number;
  pierce: number;
  status?: EnemyStatusId;
  statusChance: number;
  /** Share of the HP a hit actually removes that heals the caster (drain moves). */
  drain?: number;
  /** Made at Bill's machine (content/fusions.ts), never taught by a card; levels are ★ stars. */
  fusion?: true;
  stats: readonly UpgradeStat[];
  ref: string;
}

