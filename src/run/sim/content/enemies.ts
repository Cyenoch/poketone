export interface EnemyDef<Id extends string = EnemyId> {
  id: Id;
  name: string;
  /** Reuse an existing species GLB for a distinct guardian. */
  model?: Id;
  ghost?: true;
  types: readonly ElementType[];
  hp: number;
  speed: number;
  dmg: number;
  radius: number;
  /** 韧性 0–1: the share of every push and pull it shrugs off (sim/poise.ts; elites ≥ 0.7, guardians 1). */
  poise: number;
  xp: number;
  /** Rendered height in world units. */
  height: number;
  mobility: MobilityProfile;
  /** Its attack (sim/skills/) and the mean seconds between uses. */
  skill?: { kind: SkillId; every: number };
  /** Touching the player inflicts this status for `CONTACT_SECONDS` (params/combat.ts). */
  contact?: { status: PlayerStatusId };
  /** How it bends its chase heading (sim/movement.ts). */
  move?: EnemyMove;
}

